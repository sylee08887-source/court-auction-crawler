def region_label(code):
    return CODE_TO_NAME.get(code, code)


def resolve(tokens):
    """'영등포구', '11560', '서울 전체', '서울특별시 중구' 같은 입력을 코드 목록으로 변환."""
    codes = []
    for tok in tokens:
        tok = tok.strip()
        if not tok:
            continue
        if tok.isdigit() and len(tok) == 5:
            codes.append(tok)
        elif tok in PRESETS:
            codes.extend(PRESETS[tok])
        else:
            hits = [c for c, name in CODE_TO_NAME.items() if name == tok or name.endswith(" " + tok)]
            if not hits:
                raise ValueError(f"지역을 찾을 수 없습니다: {tok} (5자리 코드로 입력하세요)")
            if len(hits) > 1:
                names = ", ".join(CODE_TO_NAME[c] for c in hits)
                raise ValueError(f"'{tok}'이(가) 여러 지역에 해당합니다: {names} -> 시도명을 붙이거나 코드로 입력하세요")
            codes.extend(hits)
    return list(dict.fromkeys(codes))
